"""Абстрактный базовый класс суррогатной модели.

Определяет интерфейс, которому должны следовать все суррогатные модели.
Замена конкретной реализации не требует изменения алгоритмов —
достаточно подставить другой класс, наследующий BaseSurrogateModel.
"""

from abc import ABC, abstractmethod
import numpy as np


class BaseSurrogateModel(ABC):
    """Интерфейс суррогатной модели для оценки качества решений.

    Суррогатная модель обучается на парах (кодировка_решения, значение_ЦФ)
    и предсказывает значение целевой функции для новых решений,
    заменяя дорогостоящие точные вычисления.
    """

    @abstractmethod
    def fit(self, X: np.ndarray, y: np.ndarray) -> None:
        """Обучить модель на обучающих данных.

        Args:
            X: Матрица признаков (n_samples, n_features) — кодировки решений.
            y: Вектор целевых значений (n_samples,) — значения целевой функции.
        """

    @abstractmethod
    def predict(self, X: np.ndarray) -> np.ndarray:
        """Предсказать значения целевой функции.

        Args:
            X: Матрица признаков (n_samples, n_features).

        Returns:
            Вектор предсказаний (n_samples,).
        """

    @abstractmethod
    def is_ready(self) -> bool:
        """Возвращает True, если модель обучена и готова к предсказаниям."""

    @abstractmethod
    def score(self, X: np.ndarray, y: np.ndarray) -> float:
        """Оценка качества модели (R² на переданных данных).

        Args:
            X: Матрица признаков.
            y: Истинные значения целевой функции.

        Returns:
            Коэффициент детерминации R² (от -∞ до 1.0).
        """
